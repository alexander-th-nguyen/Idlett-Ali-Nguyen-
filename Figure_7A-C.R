#Metaboanalyst_participant1
mSet<-InitDataObjects("conc", "stat", FALSE, 150)
mSet<-Read.TextData(mSet, "Replacing_with_your_file_path", "colu", "disc");
mSet<-SanityCheckData(mSet)
mSet<-PerformSanityClosure (mSet);
mSet<-CheckContainsBlank(mSet)
mSet<-FilterVariable(mSet, "F", 20, "none", -1, "mean", 0, F,10.0)
mSet<-PreparePrenormData(mSet)
mSet<-Normalization(mSet, "SumNorm", "LogNorm", "NULL", ratio=FALSE, ratioNum=20)
mSet<-PlotNormSummary(mSet, "norm_0_", "png", 150, width=NA)
mSet<-PlotSampleNormSummary(mSet, "snorm_0_", "png", 150, width=NA)
mSet<-PLSR.Anal(mSet, reg=TRUE)
mSet<-PlotPLSPairSummary(mSet, "pls_pair_0_", "png", 96, width=NA, 5)
mSet<-PlotPLS2DScore(mSet, "pls_score2d_0_", "png", 150, width=NA, 1,2,0.95,0,0, "na")
mSet<-PlotPLS3DScoreImg(mSet, "pls_score3d_0_", "png", 150, width=NA, 1,2,3, 40)
mSet<-PlotPLSLoading(mSet, "pls_loading_0_", "png", 150, width=NA, 1, 2);
mSet<-PlotPLS3DLoading(mSet, "pls_loading3d_0_", "json", 1,2,3)
mSet<-PlotPLS.Imp(mSet, "pls_imp_0_", "png", 150, width=NA, "vip", "Comp. 1", 15,FALSE)
mSet<-PlotPLSBiplot(mSet, "pls_biplot_0_", "png", 150, width=NA, 1,2,10)
mSet<-PlotSubHeatMap(mSet, "heatmap_1_", "png", 150, width=NA, "norm", "row", "euclidean", "ward.D","bwm", 8,8, 10.0,0.02,10, 10, "tanova", 25, T, T, T, F, T, T, T,T,"detail")
mSet<-Volcano.Anal(mSet, FALSE, 2.0, 0, F, 0.1, TRUE, "raw", "classical")
mSet<-PlotVolcano(mSet, "volcano_0_",1, 0, "png", 150, width=NA, 5)
mSet<-SetCurrentComparison(mSet, "0hr", "1hr")
mSet<-Volcano.Anal(mSet, FALSE, 2.0, 0, F, 0.05, TRUE, "raw", "classical")
mSet<-PlotVolcano(mSet, "volcano_1_",1, 0, "png", 150, width=NA, 5)
mSet<-SetCurrentComparison(mSet, "0hr", "2.5hr")
mSet<-Volcano.Anal(mSet, FALSE, 2.0, 0, F, 0.05, TRUE, "raw", "classical")
mSet<-PlotVolcano(mSet, "volcano_2_",1, 0, "png", 150, width=NA, 5)
mSet<-SetCurrentComparison(mSet, "0hr", "2.5hr")
mSet<-Volcano.Anal(mSet, FALSE, 2.0, 1, F, 0.05, TRUE, "raw", "classical")
mSet<-PlotVolcano(mSet, "volcano_3_",1, 0, "png", 150, width=NA, 5)
